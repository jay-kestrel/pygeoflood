/* SPDX-License-Identifier: GPL-3.0-or-later
 * Shim between the ctypes adapter (pygeoflood/_cobol.py) and the
 * cobc-generated anisodiff kernel (spec D1, art_QEojt4gd).
 *
 * The shim owns the one-time GnuCOBOL runtime startup: direct ctypes
 * entry into a cobc-generated module without cob_init() segfaults, so
 * this wrapper is load-bearing, not optional. The kernel itself stays a
 * pure function of the buffers it receives. Every parameter is passed
 * BY REFERENCE (cobc convention), hence the pointer-heavy signature.
 */
#include "libcob.h"

#include <math.h>
#include <stdlib.h>
#include <string.h>

/* libm passthroughs for the transcendental path. GnuCOBOL 3.2's FUNCTION
 * EXP evaluates through GMP multi-precision floats (libcob/intrinsic.c
 * cob_intr_exp): ~124 us per call, which makes a pipeline-scale raster a
 * multi-hour computation. libm expf matches the frozen NumPy reference
 * within 1 ulp. Results are written through a pointer because GnuCOBOL's
 * dynamic CALL machinery casts the return as int — a float return is not
 * readable through RETURNING. Resolved at runtime via dlsym, so the
 * adapter must load the shared object with RTLD_GLOBAL. */
void cobol_expf(float x, float *out) { *out = expf(x); }
void cobol_exp(double x, double *out) { *out = exp(x); }

/* Generated by `cobc -C anisodiff.cob` from PROGRAM-ID ANISODIFF-C.
 * Argument order mirrors the PROCEDURE DIVISION USING list. */
extern int ANISODIFF__C(
    unsigned char *in_buf, unsigned char *scratch, unsigned char *out_buf,
    int *rows, int *cols, int *size, int *niter, int *option,
    double *kappa, double *gamma, double *step_s, double *step_e,
    int *prec, int *rc);

static int cobol_ready = 0;

/* Scratch plane for the kernel's Jacobi double buffering; allocated per
 * call, freed before return. rc values: 0 ok, 2 out of memory. */
int anisodiff_cobol(
    const float *img, int rows, int cols, int niter, int option,
    double kappa, double gamma, double step_s, double step_e, int prec,
    float *out)
{
    if (!cobol_ready) {
        cob_init(0, NULL);
        cobol_ready = 1;
    }
    const int size = rows * cols;
    int rc = 0;
    if (size <= 0 || niter <= 0) {
        /* Kernel never sees these (the adapter short-circuits), but a
         * defensive copy keeps the buffer contract if that changes. */
        if (size > 0) {
            memcpy(out, img, (size_t)size * sizeof(float));
        }
        return 0;
    }
    float *scratch = malloc((size_t)size * sizeof(float));
    if (scratch == NULL) {
        return 2;
    }
    int arg_size = size;
    int arg_rows = rows;
    int arg_cols = cols;
    int arg_niter = niter;
    int arg_option = option;
    ANISODIFF__C(
        (unsigned char *)img, (unsigned char *)scratch,
        (unsigned char *)out, &arg_rows, &arg_cols, &arg_size, &arg_niter,
        &arg_option, &kappa, &gamma, &step_s, &step_e, &prec, &rc);
    free(scratch);
    return rc;
}
